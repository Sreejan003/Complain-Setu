import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../src/services/coordinationControls.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {permittedTaskTransitions}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const view={status:'Active',capabilities:{full:true,writable:true,authority:false,leadHead:false,leadOfficer:false,receivingHead:false}};
const task={status:'Pending',assignedOfficerId:'peer',assignedBureauId:'PGRC'};
assert.deepEqual(permittedTaskTransitions(view,task,'peer','PGRC'),['In Progress']);
assert.deepEqual(permittedTaskTransitions(view,task,'other','PGRC'),[]);
assert.deepEqual(permittedTaskTransitions(view,{...task,status:'Submitted'},'peer','PGRC'),[]);
const lead={...view,capabilities:{...view.capabilities,leadOfficer:true}};
assert.deepEqual(permittedTaskTransitions(lead,{...task,status:'Submitted'},'lead','RB'),['Accepted','Rework']);
assert.deepEqual(permittedTaskTransitions({...view,capabilities:{...view.capabilities,receivingHead:true}},{...task,status:'Submitted'},'head','RO'),[]);
assert.deepEqual(permittedTaskTransitions({...lead,capabilities:{...lead.capabilities,writable:false}},task,'lead','RB'),[]);
assert.deepEqual(permittedTaskTransitions({...view,status:'Completed'},task,'peer','PGRC'),[]);
const ui=fs.readFileSync(new URL('../src/components/common/CrossBureauCoordinationWorkspace.tsx',import.meta.url),'utf8');
assert.ok(ui.includes('value={v}>{localizeLabel(v)}'),'Translated priority option must keep its canonical value');
console.log('PASS Coordination UI: assigned-only task actions, independent review, Bureau scope, frozen/completed state, and canonical localized option values.');
