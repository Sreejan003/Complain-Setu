import assert from "node:assert/strict";
import {defaultSlaPolicies} from "../config/slaPolicy.js";
import {addPolicyDays,clockDeadline,deadlineDaysRemaining,initialCaseSla,pauseDays,policyDay,selectSlaPolicy,validCivilDate} from "../services/slaCalendar.js";
const config=defaultSlaPolicies(),policy={...config.policies[0],calendar:"business" as const,holidays:["2026-11-02"]};
assert.equal(validCivilDate("2026-02-30"),false);assert.equal(validCivilDate("2028-02-29"),true);
assert.equal(addPolicyDays("2026-10-30",1,policy),"2026-11-03");
assert.equal(addPolicyDays("2026-10-30",3,policy),"2026-11-05");
assert.equal(addPolicyDays("2026-10-30",3,{...policy,calendar:"calendar"}),"2026-11-02");
assert.equal(policyDay(new Date("2026-10-30T23:30:00Z"),"Asia/Kolkata"),"2026-10-31");
assert.equal(policyDay(new Date("2026-10-30T00:30:00Z"),"America/New_York"),"2026-10-29");
assert.equal(addPolicyDays("2026-03-06",1,{...policy,timezone:"America/New_York"}),"2026-03-09");
assert.equal(selectSlaPolicy(config,{priority:"High"},new Date("2026-10-30"))?.days,15);
const custom={...policy,id:"custom",precedence:100,priorities:[],categories:[],caseTypes:[],effectiveFrom:"2026-10-30",effectiveTo:"2026-10-30",days:3};
const configured={...config,policies:[...config.policies,custom]};
assert.equal(selectSlaPolicy(configured,{priority:"High"},new Date("2026-10-30"))?.id,"custom");
assert.equal(selectSlaPolicy(configured,{priority:"High"},new Date("2026-10-31"))?.id,"operational-high");
const clock=initialCaseSla(configured,{priority:"High",createdAt:"2026-10-30T00:00:00Z"},"test",new Date("2026-10-30"));
assert.equal(clock.baseDeadline,"2026-11-05");
clock.pauses=[{from:"2026-10-30",to:"2026-11-04",reason:"test",actorId:"test",calendar:"business",holidays:["2026-11-02"]}];
assert.equal(pauseDays(clock,"2026-11-10"),2);assert.equal(clockDeadline(clock,"2026-11-10"),"2026-11-09");
clock.creditedPauseDays=2;assert.equal(clockDeadline(clock,"2026-11-10"),"2026-11-05");
assert.equal(initialCaseSla(config,{priority:"High"},"test",new Date("2026-10-30"),"2026-12-01").baseDeadline,"2026-12-01");
assert.throws(()=>initialCaseSla({...config,policies:[{...custom,startBasis:"source_received_date"}]},{priority:"High"},"test",new Date("2026-10-30")),/valid source date/);
assert.equal(deadlineDaysRemaining({expectedDisposalDate:"2026-10-30",sla:{...clock,policy:{...clock.policy,timezone:"Asia/Kolkata"}}},new Date("2026-10-30T23:30:00Z")),-1);
console.log("SLA calendar, holiday, timezone, matching, pause and manual deadline checks passed.");
