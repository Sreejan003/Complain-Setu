# Apply additional Indian languages with fallback to Hindi / base script where applicable
def get_lang_trans(code):
    if code in TRANS:
        return TRANS[code]
    # Check parent or regional similarity
    if code in ["mai", "bho", "ne", "sa", "doi", "kok"]:
        # Devanagari script languages - use adapted Hindi
        base = copy.deepcopy(TRANS["hi"])
        return base
    elif code == "as":
        # Assamese - adapted Bengali
        base = copy.deepcopy(TRANS["bn"])
        base["inst"]["directory"] = "প্ৰতিষ্ঠান ডেচব’ৰ্ড"
        base["coord"]["title"] = "ব্যুৰো সমন্বয়"
        return base
    elif code in ["ur", "ks-Arab", "sd-Arab"]:
        # Perso-Arabic scripts - adapted Urdu
        base = copy.deepcopy(TRANS["hi"])
        base["inst"]["directory"] = "ادارے کا ڈیش بورڈ"
